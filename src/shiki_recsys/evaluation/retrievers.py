from collections.abc import Callable
from dataclasses import dataclass

import pandas as pd

from shiki_recsys.evaluation.ground_truth import build_positive_items_by_user
from shiki_recsys.evaluation.metrics import (
    catalog_coverage_at_k,
    recall_at_k,
)
from shiki_recsys.evaluation.retriever_analysis import (
    RetrieverContribution,
    analyze_retriever_contributions,
    candidate_jaccard_matrix,
    candidate_union_recall,
)
from shiki_recsys.preprocessing.known_items import build_known_items
from shiki_recsys.retrievers.common import RetrieverName
from shiki_recsys.retrievers.content_tfidf import ContentTFIDFRetriever
from shiki_recsys.retrievers.explicit_svd import ExplicitSVDRetriever
from shiki_recsys.retrievers.generation import generate_retriever_candidates
from shiki_recsys.retrievers.implicit_als import ImplicitALSRetriever
from shiki_recsys.retrievers.popularity import PopularityRetriever

CandidateProvider = Callable[
    [int, int, set[int]],
    pd.DataFrame,
]


@dataclass(frozen=True)
class RetrieverEvaluationResult:
    """Store offline retriever evaluation metrics."""

    candidate_count: int
    recall_at_k: float
    catalog_coverage_at_k: float
    evaluated_users: int


@dataclass(frozen=True)
class RetrieverCandidateRun:
    """Store candidate outputs for offline retriever analysis."""

    positive_items_by_user: dict[int, set[int]]
    candidates_by_user: dict[
        int,
        dict[RetrieverName, pd.DataFrame],
    ]


@dataclass(frozen=True)
class RetrieverRunEvaluation:
    """Store summary metrics for a multi-retriever evaluation run."""

    individual_metrics: pd.DataFrame
    union_recall: float
    contributions: list[RetrieverContribution]
    jaccard_matrix: pd.DataFrame


def evaluate_retriever(
    *,
    retrieve_candidates: CandidateProvider,
    history_interactions: pd.DataFrame,
    target_interactions: pd.DataFrame,
    positive_rating_threshold: float,
    candidate_count: int,
    catalog_size: int,
) -> RetrieverEvaluationResult:
    """
    Evaluate one retriever on future positive interactions.

    Args:
        retrieve_candidates: Function returning candidates for one user.
        history_interactions: Interactions known before the target period.
        target_interactions: Future interactions used as evaluation targets.
        positive_rating_threshold: Minimum rating considered positive.
        candidate_count: Number of candidates generated per user.
        catalog_size: Number of recommendable items in the catalog.

    Returns:
        Retriever recall, catalog coverage, and evaluation metadata.
    """
    positive_items_by_user = build_positive_items_by_user(
        target_interactions,
        positive_rating_threshold=positive_rating_threshold,
    )

    known_items_by_user = build_known_items(history_interactions)

    recommendations_by_user: dict[int, list[int]] = {}

    for user_id in positive_items_by_user:
        known_anime_ids = known_items_by_user.get(
            user_id,
            set(),
        )

        candidates = retrieve_candidates(
            user_id,
            candidate_count,
            known_anime_ids,
        )

        recommendations_by_user[user_id] = candidates["anime_id"].astype(int).tolist()

    recall = recall_at_k(
        recommendations_by_user,
        positive_items_by_user,
        k=candidate_count,
    )

    coverage = catalog_coverage_at_k(
        recommendations_by_user,
        catalog_size=catalog_size,
        k=candidate_count,
    )

    return RetrieverEvaluationResult(
        candidate_count=candidate_count,
        recall_at_k=recall.value,
        catalog_coverage_at_k=coverage.value,
        evaluated_users=recall.evaluated_users,
    )


def generate_retriever_evaluation_run(
    *,
    history_interactions: pd.DataFrame,
    target_interactions: pd.DataFrame,
    positive_rating_threshold: float,
    candidate_count: int,
    popularity: PopularityRetriever,
    explicit_svd: ExplicitSVDRetriever,
    implicit_als: ImplicitALSRetriever,
    content_tfidf: ContentTFIDFRetriever,
) -> RetrieverCandidateRun:
    """
    Generate retriever candidates for offline evaluation users.

    Args:
        history_interactions: Interactions known before the target period.
        target_interactions: Future interactions used as evaluation targets.
        positive_rating_threshold: Minimum rating considered positive.
        candidate_count: Number of candidates generated by each retriever.
        popularity: Fitted popularity retriever.
        explicit_svd: Fitted explicit SVD retriever.
        implicit_als: Fitted implicit ALS retriever.
        content_tfidf: Fitted TF-IDF retriever.

    Returns:
        Positive targets and production candidate outputs by user.
    """
    positive_items_by_user = build_positive_items_by_user(
        target_interactions,
        positive_rating_threshold=positive_rating_threshold,
    )

    known_items_by_user = build_known_items(history_interactions)

    candidates_by_user = {
        user_id: generate_retriever_candidates(
            user_id=user_id,
            known_anime_ids=known_items_by_user.get(
                user_id,
                set(),
            ),
            candidate_count=candidate_count,
            popularity=popularity,
            explicit_svd=explicit_svd,
            implicit_als=implicit_als,
            content_tfidf=content_tfidf,
        )
        for user_id in positive_items_by_user
    }

    return RetrieverCandidateRun(
        positive_items_by_user=positive_items_by_user,
        candidates_by_user=candidates_by_user,
    )


def evaluate_retriever_run(
    run: RetrieverCandidateRun,
    *,
    candidate_count: int,
    catalog_size: int,
) -> RetrieverRunEvaluation:
    """
    Evaluate individual retrievers and their combined candidate pool.

    Args:
        run: Generated offline retriever candidate run.
        candidate_count: Number of candidates evaluated per retriever.
        catalog_size: Number of recommendable items in the catalog.

    Returns:
        Individual metrics, union recall, contributions, and overlap matrix.
    """
    metric_rows = []

    for source in RetrieverName:
        recommendations_by_user = {
            user_id: (
                retriever_candidates[source]["anime_id"]
                .head(candidate_count)
                .astype(int)
                .tolist()
            )
            for user_id, retriever_candidates in run.candidates_by_user.items()
            if source in retriever_candidates
        }

        if not recommendations_by_user:
            continue

        recall = recall_at_k(
            recommendations_by_user,
            run.positive_items_by_user,
            k=candidate_count,
        )
        coverage = catalog_coverage_at_k(
            recommendations_by_user,
            catalog_size=catalog_size,
            k=candidate_count,
        )

        metric_rows.append(
            {
                "source": source.value,
                "recall_at_k": recall.value,
                "catalog_coverage_at_k": coverage.value,
                "evaluated_users": recall.evaluated_users,
            }
        )

    individual_metrics = pd.DataFrame(
        metric_rows,
        columns=[
            "source",
            "recall_at_k",
            "catalog_coverage_at_k",
            "evaluated_users",
        ],
    )

    return RetrieverRunEvaluation(
        individual_metrics=individual_metrics,
        union_recall=candidate_union_recall(
            run.candidates_by_user,
            run.positive_items_by_user,
            candidate_count=candidate_count,
        ),
        contributions=analyze_retriever_contributions(
            run.candidates_by_user,
            run.positive_items_by_user,
            candidate_count=candidate_count,
        ),
        jaccard_matrix=candidate_jaccard_matrix(
            run.candidates_by_user,
            candidate_count=candidate_count,
        ),
    )
